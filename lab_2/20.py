class Solution(object):
    def isValid(self, s):
        """
        :type s: str
        :rtype: bool
        """
        # Словарь для сопоставления закрывающих скобок с открывающими
        bracket_map = {
            ')': '(',
            '}': '{',
            ']': '['
        }
        
        # Стек для хранения открывающих скобок
        stack = []
        
        # Проходим по каждому символу в строке
        for char in s:
            # Если символ - закрывающая скобка
            if char in bracket_map:
                # Извлекаем верхний элемент стека (если стек пуст, используем заглушку '#')
                top_element = stack.pop() if stack else '#'
                
                # Проверяем, соответствует ли верхний элемент стеку текущей закрывающей скобке
                if bracket_map[char] != top_element:
                    return False
            else:
                # Если символ - открывающая скобка, добавляем её в стек
                stack.append(char)
        
        # В конце стек должен быть пустым (все скобки закрыты)
        return not stack