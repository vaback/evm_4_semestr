class Solution(object):
    def evalRPN(self, tokens):
        # Стек для хранения операндов
        stack = []
        
        # Множество операторов для быстрой проверки
        operators = set(['+', '-', '*', '/'])
        
        for token in tokens:
            # Если токен - оператор
            if token in operators:
                # Извлекаем два верхних элемента из стека
                # Важно: сначала извлекаем второй операнд, потом первый
                # (потому что в RPN порядок имеет значение для вычитания и деления)
                b = stack.pop()  # правый операнд
                a = stack.pop()  # левый операнд
                
                # Выполняем операцию и помещаем результат в стек
                if token == '+':
                    result = a + b
                elif token == '-':
                    result = a - b
                elif token == '*':
                    result = a * b
                elif token == '/':
                    # Деление с округлением к нулю
                    # Для Python нужно учитывать, что // ведёт себя по-разному с отрицательными числами
                    result = int(a / b)  # int() обрезает дробную часть к нулю
                
                stack.append(result)
            else:
                # Если токен - число, преобразуем в int и добавляем в стек
                stack.append(int(token))
        
        # В конце в стеке остаётся результат
        return stack[0]